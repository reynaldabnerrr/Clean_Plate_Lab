/**
 * Full meal catalog with verified nutrition data for all protein tiers (25/40/60/80/100g).
 * `protein` stays as the DEFAULT TIER number (40) so the tier selector works correctly.
 * Top-level macro snapshot fields (calories, carbs, fat, etc.) reflect the 40g tier.
 * @type {Meal[]}
 */
export const meals = mealCatalog.map((meal) => {
  const snap = meal.nutritionByTier[meal.protein] ?? {};
  return {
    ...meal,
    // protein stays as 40 — used as the default tier selector, not overwritten
    calories: snap.calories ?? 0,
    carbs: snap.carbs ?? 0,
    fat: snap.fat ?? 0,
    fiber: snap.fiber ?? 0,
    sodium: snap.sodium ?? 0,
    potassium: snap.potassium ?? 0,
  };
});

export const featuredMeals = meals.filter((meal) => meal.featured);

export function getMealById(id) {
  return meals.find((meal) => meal.id === id);
}

export function getMealsByWeek(week) {
  return meals.filter((meal) => meal.week === week);
}

export function getNutritionForTier(meal, proteinTier) {
  return meal?.nutritionByTier?.[Number(proteinTier)] || null;
}
